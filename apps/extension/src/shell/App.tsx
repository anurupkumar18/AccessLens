import React, { useEffect, useState } from 'react';
import { AccessPackSchema, InMemorySessionClient, type AccessPack, type LiveEvent, type SessionClient } from '../shared/contracts';
import { defaultPreferences, loadPreferences, savePreferences, type StudentPreferences } from '../shared/preferences';
import { BroadcastSessionClient, hasBroadcastChannel } from '../shared/broadcastSessionClient';
import { InstructorPanel } from '../instructor';
import { createDisplayMediaHost, type CaptureHost, type Scheduler } from '../sources/screen';
import hnswDraftPack from '../../../../packs/hnsw/pack.draft.json';
import { RoleNav, type Role } from './RoleNav';
import { ErrorBoundary } from './ErrorBoundary';

// Local demo transport: instructor and student tabs in the same browser
// profile follow each other with no network. Part 4's relay replaces it.
const defaultClient: SessionClient = hasBroadcastChannel() ? new BroadcastSessionClient() : new InMemorySessionClient();
// Constructing the host calls nothing; capture starts only from the panel's
// Start button (charter A1).
const defaultHost = createDisplayMediaHost();
// Demo pack: built by scripts/build-pack.ts from the HNSW deck. It is a DRAFT
// (charter A3): Claude-generated descriptions the instructor has not yet
// reviewed. Rename to pack.json after review and update this import.
const defaultPack: AccessPack = AccessPackSchema.parse(hnswDraftPack);
const defaultPackIsDraft = true;

interface Props {
  client?: SessionClient;
  pack?: AccessPack;
  host?: CaptureHost;
  scheduler?: Scheduler;
}

export function App({ client = defaultClient, pack = defaultPack, host = defaultHost, scheduler }: Props): React.ReactElement {
  const packIsDraft = pack === defaultPack && defaultPackIsDraft;
  const [role, setRole] = useState<Role>('instructor');
  const [event, setEvent] = useState<LiveEvent | null>(null);
  const [preferences, setPreferences] = useState<StudentPreferences>(defaultPreferences);
  const [joinCode, setJoinCode] = useState('');
  const [joined, setJoined] = useState<string | null>(null);
  const [joinError, setJoinError] = useState<string | null>(null);

  useEffect(() => client.subscribe(setEvent), [client]);
  useEffect(() => { loadPreferences().then(setPreferences); }, []);

  async function joinSession(e: React.FormEvent): Promise<void> {
    e.preventDefault();
    const code = joinCode.trim().toUpperCase();
    if (!code) { setJoinError('Enter the join code your instructor shows.'); return; }
    try {
      await client.join(code);
      setJoined(code);
      setJoinError(null);
      setEvent(null);
    } catch (error) {
      setJoinError(error instanceof Error ? error.message : String(error));
    }
  }

  function toggleReducedMotion(): void {
    const next = { ...preferences, reducedMotion: !preferences.reducedMotion };
    setPreferences(next);
    void savePreferences(next);
  }

  return (
    <ErrorBoundary>
      <main>
        <header>
          <h1>AccessLens</h1>
          <p>Accessible, instructor-authorized lesson sharing</p>
        </header>
        <RoleNav role={role} onSelect={setRole} />
        {role === 'instructor' ? (
          <>
            {packIsDraft && (
              <p role="note" className="draft-note">Draft pack: slide descriptions were generated by Claude and have not been instructor-reviewed yet. Review <code>packs/hnsw/pack.draft.json</code> before a real class.</p>
            )}
            <InstructorPanel client={client} pack={pack} host={host} scheduler={scheduler} />
          </>
        ) : (
          <section>
            <h2>Student</h2>
            <p className="muted">Follows the instructor's reviewed slide. Your display preferences stay on this device.</p>
            <form onSubmit={joinSession}>
              <label htmlFor="join-code">Join code from your instructor</label>
              <input id="join-code" type="text" autoComplete="off" spellCheck={false} value={joinCode} onChange={e => setJoinCode(e.target.value)} placeholder="e.g. G4Q45J" />
              <button type="submit" className="primary">{joined ? 'Rejoin' : 'Join session'}</button>
              {joined && <p className="muted">Joined session {joined}.</p>}
              {joinError && <p role="alert">{joinError}</p>}
            </form>
            <p role="status">{event && 'regionId' in event ? `Following ${event.regionId} on ${event.assetId}.` : event ? `Instructor: ${event.type.replace('.', ' ')}.` : joined ? 'Joined. Waiting for the instructor.' : 'Waiting for instructor event.'}</p>
            <p>
              <label htmlFor="reduced-motion-toggle">
                <input id="reduced-motion-toggle" type="checkbox" checked={preferences.reducedMotion} onChange={toggleReducedMotion} />
                {' '}Reduce motion
              </label>
            </p>
          </section>
        )}
      </main>
    </ErrorBoundary>
  );
}
