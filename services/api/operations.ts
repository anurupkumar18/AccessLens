export const getJob: OperationHandler = async event => {
  if (!jobsTable) throw new ApiHttpError(500, 'configuration_error', 'The jobs table is not configured.');
  const jobId = pathParameter(event, 'jobId');
  const result = await ddb.send(new GetCommand({ TableName: jobsTable, Key: { jobId } }));
  if (!result.Item) throw new ApiHttpError(404, 'job_not_found', `No job exists for ${jobId}.`);
  const job = JobRecordSchema.safeParse(result.Item);
  if (!job.success) throw new Error(`Stored job ${jobId} does not match JobRecordSchema`);
  return respond(getJobRoute, {
    jobId: job.data.jobId,
    status: job.data.status,
    packId: job.data.packId,
    slides: job.data.slides,
    ...(job.data.error === undefined ? {} : { error: job.data.error }),
  });
};

export const listPackVersions: OperationHandler = async event => {
  if (!packsBucket) throw new ApiHttpError(500, 'configuration_error', 'The packs bucket is not configured.');
  const packId = pathParameter(event, 'packId');
  const listed = await s3.send(new ListObjectsV2Command({ Bucket: packsBucket, Prefix: `packs/${packId}/` }));
  const versions = (listed.Contents ?? []).flatMap(object => {
    const key = object.Key ?? '';
    const match = key.match(new RegExp(`^packs/${escapeRegExp(packId)}/(\\d+)\\.json$`, 'u'));
    if (!match || !object.LastModified) return [];
    const versionNumber = Number(match[1]);
    if (!Number.isSafeInteger(versionNumber) || versionNumber <= 0) return [];
    return [{
      version: versionNumber,
      publishedAt: object.LastModified.toISOString(),
      packUrl: `${assetBaseUrl}/packs/${encodeURIComponent(packId)}/${versionNumber}.json`,
    }];
  }).sort((a, b) => b.version - a.version);
  return respond(versionsRoute, { packId, versions });
};

export const getPack: OperationHandler = async event => {
  if (!packsBucket) throw new ApiHttpError(500, 'configuration_error', 'The packs bucket is not configured.');
  const packId = pathParameter(event, 'packId');
  const versionParameter = pathParameter(event, 'version');
  const packVersion = parsePositiveInteger(versionParameter, 'version');
  const key = `packs/${packId}/${packVersion}.json`;
  let object;
  try {
    object = await s3.send(new GetObjectCommand({ Bucket: packsBucket, Key: key }));
  } catch (error) {
    if (isNotFound(error)) throw new ApiHttpError(404, 'pack_not_found', `No published pack exists for ${packId} v${packVersion}.`);
    throw error;
  }
  if (!object.Body) throw new Error(`Pack object ${key} had no body`);
  const body = await object.Body.transformToString();
  let value: unknown;
  try { value = JSON.parse(body); } catch { throw new Error(`Pack object ${key} was not JSON`); }
  const pack = AccessPackSchema.safeParse(value);
  if (!pack.success) throw new Error(`Stored pack ${key} does not match AccessPackSchema`);
  return respond(packRoute, pack.data);
};

export const getArtifactManifest: OperationHandler = async event => {
  if (!artifactsBucket) throw new ApiHttpError(500, 'configuration_error', 'The artifacts bucket is not configured.');
  const artifactId = pathParameter(event, 'artifactId');
  const artifactVersion = parsePositiveInteger(pathParameter(event, 'artifactVersion'), 'artifactVersion');
  const key = `artifacts/${artifactId}/${artifactVersion}/manifest.json`;
  let object;
  try {
    object = await s3.send(new GetObjectCommand({ Bucket: artifactsBucket, Key: key }));
  } catch (error) {
    if (isNotFound(error)) throw new ApiHttpError(404, 'artifact_not_found', `No artifact manifest exists for ${artifactId} v${artifactVersion}.`);
    throw error;
  }
  if (!object.Body) throw new Error(`Artifact object ${key} had no body`);
  const body = await object.Body.transformToString();
  let value: unknown;
  try { value = JSON.parse(body); } catch { throw new Error(`Artifact object ${key} was not JSON`); }
  const manifest = ArtifactManifestSchema.safeParse(value);
  if (!manifest.success) throw new Error(`Stored artifact ${key} does not match ArtifactManifestSchema`);
  return respond(artifactRoute, manifest.data);
};

function createPublishStore(bucket: string) {
  return {
    async list(prefix: string) {
      const result = await s3.send(new ListObjectsV2Command({ Bucket: bucket, Prefix: prefix }));
      return ((result as { Contents?: Array<{ Key?: string }> }).Contents ?? []).flatMap(item => item.Key ? [item.Key] : []);
    },
    async read(key: string) {
      const result = await s3.send(new GetObjectCommand({ Bucket: bucket, Key: key })) as { Body?: unknown };
      if (!result.Body) throw new Error(`S3 object ${key} had no body`);
      if (result.Body && typeof result.Body === 'object' && 'transformToByteArray' in result.Body) {
        return (result.Body as { transformToByteArray: () => Promise<Uint8Array> }).transformToByteArray();
      }
      if (result.Body instanceof Uint8Array) return result.Body;
      throw new Error(`S3 object ${key} had no readable body`);
    },
    async write(key: string, body: Uint8Array | string, contentType?: string) {
      await s3.send(new PutObjectCommand({ Bucket: bucket, Key: key, Body: body, ...(contentType ? { ContentType: contentType } : {}) }));
    },
    async copy(source: string, destination: string, contentType?: string) {
      const { CopyObjectCommand } = await import('@aws-sdk/client-s3');
      await s3.send(new CopyObjectCommand({ Bucket: bucket, Key: destination, CopySource: `${bucket}/${source}`, ...(contentType ? { ContentType: contentType, MetadataDirective: 'REPLACE' as const } : {}) }));
    },
  };
}

