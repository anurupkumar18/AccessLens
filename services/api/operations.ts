function parsePositiveInteger(value: string, name: string): number {
  if (!/^\d+$/u.test(value)) throw new ApiHttpError(400, 'invalid_path_parameter', `${name} must be a positive integer.`);
  const parsed = Number(value);
  if (!Number.isSafeInteger(parsed) || parsed <= 0) throw new ApiHttpError(400, 'invalid_path_parameter', `${name} must be a positive integer.`);
  return parsed;
}

function isNotFound(error: unknown): boolean {
  return typeof error === 'object' && error !== null && ('$metadata' in error || 'name' in error)
    && ((error as { name?: string }).name === 'NoSuchKey' || (error as { $metadata?: { httpStatusCode?: number } }).$metadata?.httpStatusCode === 404);
}

function escapeRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/gu, '\\$&');
}

