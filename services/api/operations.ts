function s3ObjectKey(uploadId: string, filename: string): string {
  // Upload IDs are generated by the service and filenames are only used as a
  // suffix, so a client cannot escape the decks prefix.
  const safeName = filename.replace(/[^a-zA-Z0-9._-]/gu, '_').slice(-255);
  return `uploads/${uploadId}/${safeName}`;
}

